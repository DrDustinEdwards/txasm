// Writes public/_headers, the headers Cloudflare's asset server puts on the static files (which never run the
// Worker), from the set the Worker applies (app/lib/header-set.ts). `npm run build` runs it first, so a deploy always
// carries the current set; the file is committed too, for the family check to read.
import { writeFileSync } from "node:fs";
import { corpFor, headersFile } from "@dustinedwards/site-runtime/headers";
import { SECURITY_HEADERS } from "../app/lib/header-set.ts";

writeFileSync(
  new URL("../public/_headers", import.meta.url),
  headersFile(SECURITY_HEADERS, {
    comment: "GENERATED by scripts/gen-headers.mjs from app/lib/header-set.ts. Do not edit.",
    charset: true,
    // Vite names each built file by its content hash, so a year is safe; files at stable paths (favicon, logo) keep
    // the default revalidation. Cross-Origin-Resource-Policy follows what the files are (corpFor: scripts, styles and
    // fonts are cross-origin).
    paths: {
      "/assets/*": { "Cache-Control": "public, max-age=31536000, immutable", "Cross-Origin-Resource-Policy": corpFor("text/css") },
      // The islands /site.js starts (devkit's siteScript) are named by their content too. /site.js itself keeps one
      // path, so it keeps the default revalidation.
      "/islands/*": { "Cache-Control": "public, max-age=31536000, immutable", "Cross-Origin-Resource-Policy": corpFor("text/javascript") },
      "/fonts/*": { "Cross-Origin-Resource-Policy": corpFor("font/woff2") },
    },
  }),
);
